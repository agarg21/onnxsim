#!/usr/bin/env python3
"""Generate RosDiscoveryParams.tla from the ROS2 bridge's parameter defaults.

The lease length in the TLA+ model is discovery_timeout / announce_period, so
the model must follow the defaults in ros2_bridge.cpp. This script reads those
defaults and writes the derived constant. CI runs it with --check, so a change
to the defaults fails the build until the generated module is regenerated.
"""

import argparse
import pathlib
import re
import sys

HERE = pathlib.Path(__file__).resolve().parent
BRIDGE = HERE.parent / "ros2_bridge.cpp"
OUTPUT = HERE / "RosDiscoveryParams.tla"


def default_for(source, name):
    pattern = r'declare_parameter<int>\(\s*"%s"\s*,\s*(\d+)\s*\)' % re.escape(name)
    matches = re.findall(pattern, source)
    if len(matches) != 1:
        sys.exit(f"gen_params: expected one default for {name}, found {len(matches)}")
    return int(matches[0])


def render(source):
    timeout_ms = default_for(source, "discovery_timeout_ms")
    period_ms = default_for(source, "announce_period_ms")
    # The bridge clamps the announce period with std::max(100, announce_period_ms_).
    period_ms = max(100, period_ms)
    if timeout_ms % period_ms != 0:
        sys.exit("gen_params: discovery_timeout_ms is not a multiple of the announce period")
    lease_ticks = timeout_ms // period_ms
    return (
        "---- MODULE RosDiscoveryParams ----\n"
        "\\* GENERATED by gen_params.py from tools/onnx-remote/ros2_bridge.cpp. Do not edit.\n"
        f"\\* discovery_timeout_ms={timeout_ms}, announce_period_ms={period_ms}\n"
        f"L == {lease_ticks}\n"
        "====\n"
    )


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail if the generated module is stale")
    args = parser.parse_args()

    text = render(BRIDGE.read_text())
    if args.check:
        current = OUTPUT.read_text() if OUTPUT.exists() else ""
        if current != text:
            sys.exit(f"gen_params: {OUTPUT.name} is stale; run tools/onnx-remote/formal/gen_params.py")
        print(f"{OUTPUT.name} is up to date")
        return
    OUTPUT.write_text(text)
    print(f"wrote {OUTPUT}")


if __name__ == "__main__":
    main()
