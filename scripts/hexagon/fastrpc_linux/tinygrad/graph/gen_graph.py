"""Turn layout.json (from capture_graph.py) into the DSP-side C file.

Writes tg_graph_gen.c: the tinygrad-rendered kernels (one copy of the shared typedef) and
tg_graph_run(), which calls them in schedule order over one aligned arena. Writes
tg_graph_gen.h with the arena size, and adds each buffer's arena base to layout.json.
"""
import argparse, json, os, re

ALIGN = 128
# Guard bytes before and after the arena. Tinygrad's conv loads are guarded in the source, but
# the compiler may speculate them into unconditional loads that read a few hundred bytes before
# the buffer they index (conv1 reads ~232 bytes before its input). Those reads must stay mapped.
GUARD = 1024

def kernel_blocks(src):
    """Return (typedefs, [function texts]) from one rendered program source."""
    lines = src.splitlines()
    typedefs = [l for l in lines if l.startswith("typedef ")]
    blocks, i = [], 0
    while i < len(lines):
        if lines[i].startswith("__attribute__((noinline)) void "):
            j = i
            while lines[j] != "}": j += 1
            blocks.append("\n".join(lines[i:j + 1]))
            i = j + 1
        else:
            i += 1
    return typedefs, blocks

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("layout_dir")
    args = ap.parse_args()
    path = os.path.join(args.layout_dir, "layout.json")
    layout = json.load(open(path))

    # Arena: every buffer gets a 128-byte aligned base; views index into it.
    base, cur = {}, GUARD
    for k in sorted(layout["buffers"], key=int):
        base[k] = cur
        cur += (layout["buffers"][k]["nbytes"] + ALIGN - 1) // ALIGN * ALIGN
    arena_bytes = cur + GUARD
    layout["arena"] = {"base": base, "bytes": arena_bytes}

    typedefs, funcs, calls = [], [], []
    for kern in layout["kernels"]:
        t, blocks = kernel_blocks(kern["src"])
        typedefs += [x for x in t if x not in typedefs]
        name_m = re.search(r"void (\w+)\(", blocks[0])
        fname = name_m.group(1)
        funcs += blocks
        args_c = []
        for a in kern["args"]:
            args_c.append(f"(void*)(g_arena + {base[str(a['key'])] + a['offset']}) /* key {a['key']} +{a['offset']} */")
        calls.append(f"  {fname}({', '.join(args_c)});")

    out_c = os.path.join(args.layout_dir, "tg_graph_gen.c")
    with open(out_c, "w") as f:
        f.write("/* Generated by gen_graph.py from tinygrad's rendered kernels. Do not edit. */\n")
        f.write('#include "tg_graph_gen.h"\n')
        f.write("\n".join(typedefs) + "\n\n")
        f.write("static unsigned char g_arena[TG_ARENA_BYTES] __attribute__((aligned(128)));\n\n")
        f.write("\n\n".join(funcs) + "\n\n")
        f.write("/* Runs the whole graph over arena (TG_ARENA_BYTES bytes), in place. */\n")
        f.write("void tg_graph_run(unsigned char* arena) {\n")
        f.write("  __builtin_memcpy(g_arena, arena, TG_ARENA_BYTES);\n")
        f.write("\n".join(calls) + "\n")
        f.write("  __builtin_memcpy(arena, g_arena, TG_ARENA_BYTES);\n}\n")
    out_h = os.path.join(args.layout_dir, "tg_graph_gen.h")
    with open(out_h, "w") as f:
        f.write("#pragma once\n")
        f.write(f"#define TG_ARENA_BYTES {arena_bytes}\n")
        f.write("void tg_graph_run(unsigned char* arena);\n")
    json.dump(layout, open(path, "w"), indent=1)
    print(f"arena={arena_bytes} bytes, kernels={len(calls)} -> {out_c}")

if __name__ == "__main__":
    main()
